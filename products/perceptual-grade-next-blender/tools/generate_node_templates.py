"""Generate the shipped native node library and Stack GLSL in pinned Blender."""

from __future__ import annotations

import argparse
from dataclasses import replace
import hashlib
import json
from pathlib import Path
import sys
from types import ModuleType, SimpleNamespace


def _sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _write_json(path, value):
    path.write_text(json.dumps(value, indent=2, sort_keys=True, allow_nan=False) + "\n",
                    encoding="utf-8", newline="\n")


def _install_packages(path):
    package = ModuleType("color_tools")
    package.__path__ = [str(path)]
    sys.modules[package.__name__] = package


def generate(packages, output_dir):
    """Emit every supported production topology from the canonical builders."""
    import bpy
    import numpy as np

    _install_packages(packages)
    from color_tools.kernel import lut
    from color_tools.kernel.boundary import prepare_boundary
    from color_tools.kernel.prepare import prepare, prepare_tone
    from color_tools.kernel.settings import SPACES, ToneSettings
    from color_tools.kernel.stage2_bindings import PARAMETER_BANK_BINDINGS, PARAMETER_IMAGE
    from color_tools.template_build.lut_shader_emitter import grade_source
    from color_tools.template_build.metadata import describe_template, tag_template
    from color_tools.template_build.stack_graph import build_stack_group
    from color_tools.template_build.stage2_graph import build_stage2_group
    from color_tools.template_build.wrapper_graph import build_wrapper_group

    if tuple(bpy.app.version) != (5, 2, 4):
        raise RuntimeError("Node templates must be generated by pinned Blender 5.2.4")
    bpy.ops.wm.read_factory_settings(use_empty=True)
    output_dir.mkdir(parents=True, exist_ok=True)
    variants = {}
    roots = set()
    boundary = None
    tree_types = ("ShaderNodeTree", "CompositorNodeTree")
    tone = ToneSettings()

    for space in SPACES:
        base = prepare(tone=tone, space=space)
        if boundary is None:
            boundary = prepare_boundary(base.fl, base.aw, base.gamma)
        prepared = replace(base, tone=prepare_tone(tone, full_fields=True),
                           boundary=boundary)
        for tree_type in tree_types:
            key = f"grade:{tree_type}:{space}"
            built = build_stage2_group(
                prepared, tree_type,
                name=f"PG Template Grade {tree_type.removesuffix('NodeTree')} {space}",
            )
            for image in built.images:
                if image.get(PARAMETER_IMAGE) is None:
                    image["perceptual_grade_nodes_field_role"] = "boundary_seed"
            record = tag_template(
                built.tree, key, "grade", space=space,
            )
            parameter_images = set()
            for bank in (0, 1):
                for name in record["slots"][f"parameter:{bank}"]:
                    reader = built.tree.nodes[name]
                    parameter_images.add(reader.image)
                    reader.image = None
            for binding in PARAMETER_BANK_BINDINGS:
                if binding in built.tree:
                    del built.tree[binding]
            for image in parameter_images:
                if image.users != 0:
                    raise RuntimeError("Grade template retained a parameter Image")
                bpy.data.images.remove(image)
            variants[key] = describe_template(
                built.tree, key, "grade", space=space,
            )
            roots.add(built.tree)

    for space in SPACES:
        to_lut, from_lut = lut.basis(space)
        for size in (lut.PREVIEW_SIZE, lut.SIZE):
            # Only topology and basis constants are retained. The image is a
            # build placeholder and is removed before library serialization.
            shape = (size, size, size, 3)
            cube = lut.LinearCube(
                np.zeros(shape, dtype=np.float32),
                np.zeros((3, *shape), dtype=np.float32),
                "node-template", space, to_lut, from_lut, size,
            )
            for tree_type in tree_types:
                key = f"stack:{tree_type}:{space}:{size}"
                tree, images = build_stack_group(
                    SimpleNamespace(cube=cube), tree_type,
                    name=f"PG Template Stack {tree_type.removesuffix('NodeTree')} {space} {size}",
                )
                record = tag_template(tree, key, "stack", space=space, size=size)
                for name in record["slots"]["lut"]:
                    tree.nodes[name].image = None
                for image in images:
                    if image.users != 0:
                        raise RuntimeError("Stack template retained a placeholder LUT Image")
                    bpy.data.images.remove(image)
                variants[key] = describe_template(
                    tree, key, "stack", space=space, size=size,
                )
                roots.add(tree)

    for tree_type in tree_types:
        key = f"wrapper:{tree_type}"
        tree = build_wrapper_group(tree_type)
        tree.name = f"PG Template Bake {tree_type.removesuffix('NodeTree')}"
        variants[key] = tag_template(tree, key, "wrapper")
        roots.add(tree)

    if boundary is None or len(variants) != 20:
        raise RuntimeError("Node template generation did not emit every supported variant")
    blend_path = output_dir / "node_templates.blend"
    shader_path = output_dir / "grade_stack.glsl"
    shader_path.write_text(grade_source(boundary) + "\n", encoding="utf-8", newline="\n")
    bpy.data.libraries.write(str(blend_path), roots, path_remap="NONE",
                             fake_user=True, compress=True)
    manifest = {
        "schema": 1,
        "blender_version": list(bpy.app.version),
        "blend_sha256": _sha256(blend_path),
        "shader_sha256": _sha256(shader_path),
        "shader_context": {name: float(getattr(boundary, name))
                           for name in ("fl", "aw", "gamma")},
        "variants": variants,
    }
    manifest_path = output_dir / "node_templates.json"
    _write_json(manifest_path, manifest)
    sources = {str(path.relative_to(packages)): _sha256(path)
               for path in sorted(packages.rglob("*")) if path.is_file()}
    sources["generate_node_templates.py"] = _sha256(Path(__file__))
    _write_json(output_dir / "report.json", {
        "schema": 1,
        "blender_version": list(bpy.app.version),
        "variant_count": len(variants),
        "source_sha256": sources,
        "asset_sha256": {path.name: _sha256(path)
                         for path in (blend_path, shader_path, manifest_path)},
        "variants": variants,
    })


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--packages", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    arguments = sys.argv[sys.argv.index("--") + 1:]
    args = parser.parse_args(arguments)
    generate(args.packages.resolve(), args.output_dir.resolve())


if __name__ == "__main__":
    main()
