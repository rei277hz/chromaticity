"""Integration checks for generated media and stable source provenance."""
import json
from pathlib import Path
import tempfile
import unittest
from unittest.mock import patch

import numpy as np

from pg_book_generators import check_demos, check_favicon, check_intro
from pg_book_generators.figure_common import manifest
from pg_book_legacy.localization.i18n import CATALOGS, tr
from pg_book_legacy.model import color, tone

RESOURCES = Path(__file__).with_name('test_resources')


class GeneratorsTest(unittest.TestCase):
    def test_legacy_model_and_compiled_catalogs(self):
        self.assertEqual(tr('product.name', locale='en'), CATALOGS['en']['product.name'])
        self.assertEqual(set(CATALOGS), {'en', 'zh_HANS'})
        # Original 1.23.2 numerical-figure probes, independent of today's model.
        model = tone.model(tone.Parameters())
        self.assertEqual((model.reference, model.peak), (203, 1000))
        np.testing.assert_allclose(model.target, [
            0.0, 0.27650145394737236, 0.5135150445963199,
            1.0, 1.8374882202130838,
        ], rtol=1e-12, atol=1e-14)
        np.testing.assert_allclose(
            color.project_hk(np.array([50., 80., 0.]), np.array([50., 20., 0.])),
            [58.18807665868112, 48.1416478163039, 0.0],
            rtol=1e-12, atol=1e-14,
        )
        self.assertEqual((color.CHROMA_SATURATION, color.CHROMA_NEUTRAL), (35.0, 2.0))

    def test_provenance_is_independent_of_checkout(self):
        with tempfile.TemporaryDirectory() as temporary:
            base = Path(temporary)
            records = []
            for name in ('first', 'different-root'):
                root = base / name
                root.mkdir()
                source = root / 'input.json'
                source.write_bytes(b'{"value": 1}\n')
                output = root / 'output'
                output.mkdir()
                (output / 'figure.png').write_bytes(b'generated bytes')
                manifest(output, [source], 'test', {'docs/data': root})
                records.append((output / 'manifest.json').read_bytes())
            self.assertEqual(*records)
            record = json.loads(records[0])
            self.assertEqual(set(record['inputs']), {'docs/data/input.json'})
            with self.assertRaisesRegex(ValueError, 'no logical provenance root'):
                manifest(output, [source], 'test', {'docs/data': base / 'unrelated'})

    def test_favicon_payloads_and_required_sources(self):
        with patch('sys.argv', ['check_favicon', '--icons', str(RESOURCES / 'icons')]):
            check_favicon.main()

    def test_movies_color_timing_and_failures(self):
        with patch('sys.argv', ['check_demos', '--spec', str(RESOURCES / 'data/demos.json')]):
            check_demos.main()

    def test_intro_output_color_timing_and_failures(self):
        with patch('sys.argv', [
            'check_intro', '--spec', str(RESOURCES / 'data/intro-video.json'),
            '--recordings', str(RESOURCES / 'intro_source'),
            '--built', str(RESOURCES / 'intro'),
        ]):
            check_intro.main()


if __name__ == '__main__':
    unittest.main()
